"""Build the single-source browser notebook without changing team calculations."""

import ast
import base64
import gzip
import hashlib
from pathlib import Path
import textwrap

ROOT = Path(__file__).resolve().parents[1]
DEST = ROOT / "designer_generator/browser_app.py"


def build():
    source_app = (ROOT / "designer_generator/app.py").read_text(encoding="utf-8")
    original_source = (ROOT / "designer_generator/original_generators.py").read_text(encoding="utf-8").split("import numpy as np\n\n", 1)[1]
    core_source = (ROOT / "designer_generator/core.py").read_text(encoding="utf-8")
    names = {"_LocalNumpy", "fit_parameters", "generate", "summary", "diagnostics"}
    wrapper_source = "\n\n".join(ast.get_source_segment(core_source, node) for node in ast.parse(core_source).body
                                 if isinstance(node, (ast.FunctionDef, ast.ClassDef)) and node.name in names)
    # Match the Git blob even when Windows checks out the CSV with CRLF.
    data = (ROOT / "ASE10.csv").read_bytes().replace(b"\r\n", b"\n")
    capsule = base64.b64encode(gzip.compress(data, mtime=0)).decode()
    encoded = "\n".join("        " + repr(line) for line in textwrap.wrap(capsule, 100))
    import_cell_end = source_app.index("\n\n@app.cell(hide_code=True)")
    tail = source_app[import_cell_end:]
    intro_end = tail.index("\n\n@app.cell\ndef _(fit_parameters, load_no2):")
    intro, remaining = tail[:intro_end], tail[intro_end:]

    header = '''# /// script
# requires-python = ">=3.11"
# dependencies = ["marimo==0.25.2", "numpy", "pandas", "scipy", "matplotlib"]
# ///

"""Browser version: exact team algorithms and original CSV embedded for WASM.

Generated by browser_build.py from app.py/core.py/original_generators.py/ASE10.csv.
The source algorithms are evaluated as Python, with no JavaScript replacement.
"""

import marimo

__generated_with = "0.25.2"
app = marimo.App(width="medium", app_title="Лабораторная № 1 · Генерация сигнала NO₂")


@app.cell
def _():
    import marimo as mo
    return (mo,)


@app.cell
def _():
    SOURCE_COMMIT = "01a1c6ce89d076e969bf0a8300fcd9abc2c96e36"
    return (SOURCE_COMMIT,)
'''
    imports = f'''

@app.cell
def _():
    import base64
    import gzip
    import hashlib
    import io
    from time import perf_counter
    from types import FunctionType, SimpleNamespace
    import numpy as np
    import pandas as pd
    import matplotlib.pyplot as plt
    from scipy import stats

    _algorithm_source = {original_source!r}
    _wrapper_source = {wrapper_source!r}
    _csv_gzip_b64 = (
{encoded}
    )
    _expected_algorithm_sha = {hashlib.sha256(original_source.encode()).hexdigest()!r}
    _expected_csv_sha = {hashlib.sha256(data).hexdigest()!r}
    assert hashlib.sha256(_algorithm_source.encode()).hexdigest() == _expected_algorithm_sha
    _csv_bytes = gzip.decompress(base64.b64decode(_csv_gzip_b64))
    assert hashlib.sha256(_csv_bytes).hexdigest() == _expected_csv_sha

    # Run the exact original Python cell in a private namespace.
    _algorithms = {{"np": np}}
    exec(compile(_algorithm_source, "<team-generator-cell>", "exec"), _algorithms)
    _original_generators = SimpleNamespace(generate_knuth=_algorithms["generate_knuth"],
                                           generate_gd=_algorithms["generate_gd"])
    _helpers = {{"np": np, "pd": pd, "stats": stats, "perf_counter": perf_counter,
                "FunctionType": FunctionType, "original_generators": _original_generators}}
    exec(compile(_wrapper_source, "<presentation-helpers>", "exec"), _helpers)
    fit_parameters = _helpers["fit_parameters"]
    generate = _helpers["generate"]
    summary = _helpers["summary"]
    diagnostics = _helpers["diagnostics"]

    def load_no2():
        return pd.read_csv(io.BytesIO(_csv_bytes), sep=";")["ASE_NO2"].dropna()

    return diagnostics, fit_parameters, generate, load_no2, np, pd, plt, stats, summary
'''
    DEST.write_text(header + intro + imports + remaining, encoding="utf-8")
    print(f"Built {DEST.relative_to(ROOT)}: {DEST.stat().st_size} bytes")


if __name__ == "__main__":
    build()
